-- 表结构与 JPA 实体映射 100% 一致（对齐法：取自 Hibernate 实际生成 DDL）
-- 列名混合策略：course_grades.student_id/course_id 与 book_copies.book_id 经
-- Spring Boot 默认下划线物理命名策略由显式注解转换而来；loans/reservations/students 等走默认下划线命名。
-- books / book_copies 主键无自增（id 由领域代码分配）；其余表为 IDENTITY 自增。

-- 先清理既有表，保证脚本幂等（与 create-drop 语义一致）：
-- 多个 Spring 测试 context 可能复用同一 jdbc:h2:mem:demo 内存库，每次执行前 DROP 再重建。
drop table if exists book_copies cascade;
drop table if exists books cascade;
drop table if exists course_grades cascade;
drop table if exists courses cascade;
drop table if exists loans cascade;
drop table if exists reservations cascade;
drop table if exists students cascade;

create table book_copies (
    book_id bigint,
    id bigint not null,
    status enum ('AVAILABLE','BORROWED','RESERVED'),
    primary key (id)
);

create table books (
    id bigint not null,
    author varchar(255),
    title varchar(255),
    primary key (id)
);

create table course_grades (
    score integer,
    course_id bigint not null,
    id bigint generated by default as identity,
    student_id bigint not null,
    primary key (id),
    constraint uk_student_course unique (student_id, course_id)
);

create table courses (
    credits integer,
    id bigint generated by default as identity,
    name varchar(255),
    primary key (id)
);

create table loans (
    borrowed_at date,
    due_date date,
    returned_at date,
    book_copy_id bigint,
    book_id bigint,
    id bigint generated by default as identity,
    reader_id bigint,
    primary key (id)
);

create table reservations (
    book_id bigint,
    created_at timestamp(6),
    id bigint generated by default as identity,
    reader_id bigint,
    status enum ('CANCELLED','FULFILLED','NOTIFIED','WAITING'),
    primary key (id)
);

create table students (
    id bigint generated by default as identity,
    email varchar(255),
    name varchar(255),
    primary key (id)
);

-- 唯一的实体间外键：books 1—N book_copies
alter table if exists book_copies
    add constraint fk_book_copies_books
    foreign key (book_id)
    references books;